/** Format a number for an exact-expression string without trailing zeros. */
function formatNumber(value: number, maxDecimals = 2): string {
  return String(Number(value.toFixed(maxDecimals)))
}

/**
 * Render a multiple of π exactly when the coefficient is a finite decimal or
 * a simple fraction with denominator 3 or 6. Returns null when no clean exact
 * form is available, so the live panel falls back to the decimal value.
 */
function piValue(coefficient: number): string | null {
  if (!Number.isFinite(coefficient) || coefficient <= 0) return null
  if (Math.abs(coefficient * 100 - Math.round(coefficient * 100)) < 1e-9) {
    return `${formatNumber(coefficient, 2)}π`
  }
  if (Math.abs(coefficient * 3 - Math.round(coefficient * 3)) < 1e-9) {
    return `${Math.round(coefficient * 3)}π/3`
  }
  if (Math.abs(coefficient * 6 - Math.round(coefficient * 6)) < 1e-9) {
    return `${Math.round(coefficient * 6)}π/6`
  }
  return null
}

/** Render an exact surd coefficient√radicand, omitting a coefficient of 1. */
function surd(coefficient: number, radicand: 2 | 3): string {
  if (Math.abs(coefficient - 1) < 1e-9) return `√${radicand}`
  return `${formatNumber(coefficient, 3)}√${radicand}`
}

/** Render √value exactly, simplifying perfect-square factors where possible. */
function sqrtExact(value: number): string {
  const root = Math.sqrt(value)
  if (Math.abs(root - Math.round(root)) < 1e-9) return String(Math.round(root))
  if (Math.abs(value - Math.round(value)) < 1e-9) {
    let radicand = Math.round(value)
    let outside = 1
    for (let factor = 2; factor * factor <= radicand; factor += 1) {
      while (radicand % (factor * factor) === 0) {
        radicand /= factor * factor
        outside *= factor
      }
    }
    if (outside > 1) return `${outside}√${radicand}`
  }
  return `√${formatNumber(value, 2)}`
}


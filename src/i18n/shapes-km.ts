/**
 * Return the shape with its reader-facing text in the requested language.
 * Ids, keys, symbols, ranges, LaTeX expressions and the `compute`/`exact`
 * functions are carried over untouched, so calculations are identical in both
 * languages. Missing Khmer entries fall back to the English text field by field.
 */
export function localizeShape(shape: Shape, language: Language): Shape {
  if (language !== 'km') return shape
  const km = kmShapeContent[shape.id]
  const copy = shapeCopy(shape, language)
  if (!km) return { ...shape, name: copy.name, tagline: copy.tagline }
  return {
    ...shape,
    name: copy.name,
    tagline: copy.tagline,
    definition: km.definition,
    properties: shape.properties.map((property, index) => km.properties[index] ?? property),
    dimensions: shape.dimensions.map((dimension) => {
      const text = km.dimensions[dimension.key]
      return text ? { ...dimension, label: text.label, description: text.description } : dimension
    }),
    metrics: shape.metrics.map((metric) => {
      const text = km.metrics[metric.key]
      return text ? { ...metric, label: text.label, description: text.description } : metric
    }),
    formulas: shape.formulas.map((formula, index) => {
      const text = km.formulas[index]
      if (!text) return formula
      return { ...formula, label: text.label, note: formula.note !== undefined ? (text.note ?? formula.note) : undefined }
    }),
    example: {
      problem: km.example.problem,
      steps: shape.example.steps.map((step, index) => km.example.steps[index] ?? step),
      answer: km.example.answer,
    },
  }
}
